class Solution {
public:
    vector<int> maxSlidingWindow(vector<int>& nums, int k) {
        int n = nums.size();
        
        // 提前分配好结果数组的空间，窗口总数为 n - k + 1
        vector<int> output(n - k + 1); 
        
        // 双端队列，存放的是元素的【索引】而非具体值
        // 核心作用：维护当前窗口内的最大值，保证队列对应的数组值严格从大到小排列
        deque<int> q;                  
        
        // l 为窗口左边界，r 为窗口右边界
        int l = 0, r = 0;              

        while (r < n) {
            // 【步骤 1：维护队列的单调递减性】
            // 如果新来的元素 nums[r] 比队尾对应的元素大，
            // 那么旧的队尾永远不可能成为最大值（因为它比新元素小，且会比新元素更早离开窗口）。
            // 必须将其弹出，直到队尾元素大于等于新元素为止。
            while (!q.empty() && nums[q.back()] < nums[r]) {
                q.pop_back();
            }
            
            // 【步骤 2：新元素入队】
            // 将当前元素的索引入队，存索引是为了后面判断它是否已经越界
            q.push_back(r);

            // 【步骤 3：清理滑出窗口的过期元素】
            // 当前窗口的有效左边界是 l。如果队首的最大值索引已经小于 l，
            // 说明这个最大值已经滑出窗口了，必须把它从队首踢掉。
            if (l > q.front()) {
                q.pop_front();
            }

            // 【步骤 4：提取当前窗口最大值，并滑动窗口】
            // 当 r 走到第 k-1 个位置时（即窗口内凑齐了 k 个元素），开始记录答案。
            if ((r + 1) >= k) {
                // 因为队列是单调递减的，队首的索引对应的元素永远是当前窗口内的最大值
                output[l] = nums[q.front()]; 
                
                // 记录完毕后，左边界向右滑动一步，准备迎接下一个窗口
                l++;                         
            }
            
            // 右边界持续向右移动，引入新元素
            r++;
        }

        return output;
    }
};